export function searchGlobalCatalog(query = "", limit = 20) {
  if (!query || !query.trim()) {
    return GLOBAL_TRANSIT_CATALOG.slice(0, limit);
  }
  const q = query.toLowerCase().trim();
  return GLOBAL_TRANSIT_CATALOG.filter((f) => {
    return (
      f.provider.toLowerCase().includes(q) ||
      f.location.toLowerCase().includes(q) ||
      f.country.toLowerCase().includes(q) ||
      f.feed_name.toLowerCase().includes(q)
    );
  }).slice(0, limit);
}
